import { launch, desktop, mobile, shot, wait, HARNESS } from './lib'
const browser = await launch()
const d = await desktop(browser)
await d.goto(HARNESS + '?wave=4&phase=gameover&stats')
await wait(1500)
await shot(d, 's6-d-gameover')
await d.goto(HARNESS + '?wave=8&phase=victory&stats')
await wait(1500)
await shot(d, 's6-d-victory')
const l = await mobile(browser, true)
await l.goto(HARNESS + '?wave=4&phase=gameover&stats&device=touch')
await wait(1500)
await shot(l, 's6-l-gameover-touch')
await l.goto(HARNESS + '?device=touch')
await wait(1200)
await shot(l, 's6-l-title-touch')
await l.goto(HARNESS + '?wave=4&start=wave&device=touch&crowd=6')
await wait(600)
await shot(l, 's6-l-wave-hud')
await browser.close()
