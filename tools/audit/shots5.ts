import { launch, desktop, mobile, shot, wait, HARNESS as GAME, model } from './lib'

const browser = await launch()

const d = await desktop(browser)
await d.goto(GAME)
await wait(1200)
await shot(d, 's5-d-01-title')
await d.keyboard.press('Enter')
await wait(900)
await shot(d, 's5-d-02-hints')
await d.keyboard.down('KeyD')
await wait(500)
await d.keyboard.up('KeyD')
await wait(300)
await shot(d, 's5-d-03-moved')
await d.mouse.move(900, 200)
await d.mouse.down()
await wait(300)
await d.mouse.up()
await wait(700)
await shot(d, 's5-d-04-startwave-hint')
await d.keyboard.press('Enter')
await wait(500)
await shot(d, 's5-d-05-wave-banner')
console.log(JSON.stringify((await model(d)).lessons))

const l = await mobile(browser, true)
await l.goto(GAME)
await wait(1200)
await shot(l, 's5-l-01-title-touch')
await l.touchscreen.tap(600, 200)
await wait(1200)
await shot(l, 's5-l-02-hints-touch')

const p = await mobile(browser, false)
await p.goto(GAME)
await wait(1200)
await shot(p, 's5-p-01-portrait')

await browser.close()
