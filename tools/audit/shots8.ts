import { launch, desktop, mobile, shot, wait } from './lib'

const BASE = process.env.BASE ?? 'http://localhost:4174/'
const browser = await launch()
const d = await desktop(browser)
await d.goto(BASE)
await wait(1500)
await shot(d, 's8-d-title-modes')
await d.goto(BASE + '?wave=8&phase=victory&stats')
await wait(1800)
await shot(d, 's8-d-victory-keep-going')
await d.goto(BASE + '?wave=12&mode=endless&phase=gameover&stats&best=14')
await wait(1800)
await shot(d, 's8-d-endless-gameover')
await d.goto(BASE + '?wave=11&mode=endless&prep=17000&gun=smg&tier=2&pistol=3')
await wait(800)
await shot(d, 's8-d-endless-prep-pips')
await d.goto(BASE + '?wave=10&mode=endless&start=wave&god&gun=shotgun&tier=3')
await wait(2500)
await d.mouse.move(900, 300)
await d.mouse.down()
await wait(70)
await shot(d, 's8-d-endless-hud-flash')
await d.mouse.up()
const l = await mobile(browser, true)
await l.goto(BASE + '?device=touch')
await wait(1500)
await shot(l, 's8-l-title-touch-modes')
await browser.close()
