import { launch, desktop, mobile, shot, wait, GAME } from './lib'
const browser = await launch()
const d = await desktop(browser)
await d.goto(GAME)
await wait(500)
await shot(d, 'd-01-ready')
await d.keyboard.press('Enter')
await wait(1200)
await shot(d, 'd-02-prep1')
await d.keyboard.down('KeyD')
await wait(400)
await d.keyboard.up('KeyD')
await d.mouse.move(900, 200)
await wait(300)
await shot(d, 'd-03-prep1-moved')
const m = await mobile(browser)
await m.goto(GAME)
await wait(500)
await shot(m, 'm-01-ready')
await m.touchscreen.tap(200, 400)
await wait(1200)
await shot(m, 'm-02-prep1')
const l = await mobile(browser, true)
await l.goto(GAME)
await wait(500)
await shot(l, 'l-01-ready')
await l.touchscreen.tap(400, 200)
await wait(1200)
await shot(l, 'l-02-prep1')
await browser.close()
