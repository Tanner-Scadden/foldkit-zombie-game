import { launch, desktop, mobile, shot, wait, HARNESS } from './lib'
const browser = await launch()
const d = await desktop(browser)
await d.goto(HARNESS + '?wave=2&prep=17000&py=40&px=150&money=200')
await wait(800)
await shot(d, 's7-d-newkind-bottom-band')
await d.goto(HARNESS + '?wave=8&phase=victory&stats')
await wait(1500)
await shot(d, 's7-d-victory')
await d.goto(HARNESS + '?wave=3&prep=15000&barricades=1')
await wait(800)
await shot(d, 's7-d-trap-hint')
const l = await mobile(browser, true)
await l.goto(HARNESS + '?device=touch')
await wait(1500)
await shot(l, 's7-l-title-touch')
await browser.close()
